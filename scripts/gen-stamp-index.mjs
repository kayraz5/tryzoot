// EDITOR: MATTHEW
// pnpm gen:stamps -> lists the artwork in public/stamps/ into src/model/data/stampIndex.js.
// Files under public/ are served as-is and never enter the module graph, so they cannot be
// found with import.meta.glob the way they could under src/assets/. The app still has to answer
// "is there a picture for this place?" synchronously — a null is what makes a caller fall back to
// the drawn chop — so the names are written out here instead of discovered at runtime.
// Run it after adding or removing a stamp.
import { readdirSync, writeFileSync } from 'node:fs'

const DIR = new URL('../public/stamps/', import.meta.url)
const OUT_FILE = new URL('../src/model/data/stampIndex.js', import.meta.url)

const names = readdirSync(DIR)
  .filter((file) => file.endsWith('.png'))
  .map((file) => file.slice(0, -4))
  .sort()

writeFileSync(OUT_FILE, `// EDITOR: MATTHEW
// Generated by \`pnpm gen:stamps\`. The artwork itself lives in public/stamps/.
export const STAMP_NAMES = new Set(${JSON.stringify(names, null, 2)})
`)
console.log(`[gen-stamps] indexed ${names.length} stamps from public/stamps/`)
